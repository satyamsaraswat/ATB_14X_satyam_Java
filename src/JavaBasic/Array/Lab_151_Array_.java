package JavaBasic.Array;

public class Lab_151_Array_ {
    public static void main(String[] args) {
        String[] batch = new String[3];
        batch[0] = "Kamla";
        batch[1] = "Bimla";
        batch[2] = "Dimple";

        System.out.println(batch[0]);
        System.out.println(batch[2]);
        System.out.println(batch[1]);


        boolean[] is_male_data = new boolean[3];
        is_male_data[0] = true;
        is_male_data[1] = true;
        is_male_data[2] = false;

        System.out.println(is_male_data[2]);
        System.out.println(is_male_data[1]);
        System.out.println(is_male_data[0]);

    }
}
